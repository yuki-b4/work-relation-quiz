-- 宣言のフォークを「出した」記録（施策a 段1・A-1の拡張）。
-- 正：集客戦略マップ.md §3.6・§3.8
--
-- フォークは結果カードの「読み解きガイドを開く」からしか出ていなかった。
-- **押さない人にこそ届かせたい**ので、結果を読み終えた人・手が止まった人にも
-- モーダルで出す（2026-09-12）。その効き目を判定するために、
-- 「出したか」と「どちらの出し方だったか」を残す。
--
--   宣言率（declared_at）だけでは、**出していないのか、出して無視されたのか**が分からない。
--   直す先が「出し方」なのか「中身」なのかも分からないので、ここを分けて測る。
--
-- 0001〜0004 は編集しない（0004 はステージングに適用済み。編集しても流れ直さない）。

alter table responses add column declare_prompted_at text;  -- フォークを最初に出した時刻
alter table responses add column declare_prompt_via  text;  -- 'cta'（ボタンを押した）| 'auto'（滞在で出した）

